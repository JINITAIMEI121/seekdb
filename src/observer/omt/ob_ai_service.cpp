int ObAiService::init()
{
  int ret = OB_SUCCESS;
  if (IS_INIT) {
    ret = OB_INIT_TWICE;
  } else if (OB_ISNULL(GCTX.sql_proxy_)) {
    ret = OB_INVALID_ARGUMENT;
    LOG_WARN("sql proxy is null when initializing ai service", K(ret));
  } else if (OB_FAIL(ai_column_timer_.init("AiColTask", ObMemAttr("AiColTask")))) {
    LOG_WARN("fail to init ai column timer", K(ret));
  } else if (OB_FAIL(ai_column_task_.init(*GCTX.sql_proxy_, *this))) {
    LOG_WARN("fail to init ai column task", K(ret));
  } else {
    is_inited_ = true;
  }
  return ret;
}

int ObAiService::start()
{
  int ret = OB_SUCCESS;
  if (IS_NOT_INIT) {
    ret = OB_NOT_INIT;
  } else if (OB_FAIL(ai_column_timer_.schedule(ai_column_task_, AI_COLUMN_TASK_PERIOD_US, true))) {
    LOG_WARN("fail to schedule ai column tasks", K(ret));
  }
  return ret;
}

